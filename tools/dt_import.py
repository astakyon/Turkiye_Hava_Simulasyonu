#!/usr/bin/env python3
"""Defence Turk "Sistem Envanteri" -> src/js/93-envanter-data.js

Kaynak: https://www.defenceturk.tr/tr/sistem-envanteri (Defence Turk; açık kaynak bilgiler).
Yalnızca olgusal alanlar alınır: ad, kategori, üretici, konfigürasyonlar, teknik özellikler, kullanıcı ülkeler, durum.
Açıklama metinleri ve görseller (telifli içerik) alınmaz; oyun içinde kaynak gösterilir.

Kullanım: python3 tools/dt_import.py ham.json
ham.json: [[ad, üst kategori, alt kategori, üretici, konfigürasyonlar, teknik özellikler, kullanıcılar, durum], ...]
"""
import json, re, sys, unicodedata

FIX = {  # ASCII yazılmış kategori adlarını tek biçime getir
    'Havacilik ve Uzay Sistemleri': 'Havacılık ve Uzay Sistemleri',
    'Deniz Araclari': 'Deniz Araçları', 'Kara Araclari': 'Kara Araçları',
    'Doner Kanatli Sistemler': 'Döner Kanatlı Sistemler', 'Sabit Kanatli Sistemler': 'Sabit Kanatlı Sistemler',
    'Insansiz Hava Araclari': 'İnsansız Hava Araçları', 'Insansız Hava Araclari': 'İnsansız Hava Araçları',
    'Paletli Araclar': 'Paletli Araçlar', 'Tekerlekli Araclar': 'Tekerlekli Araçlar', 'Ozel Amacli Araclar': 'Özel Amaçlı Araçlar',
    'Karistiricilar': 'Karıştırıcılar', 'Radar ve Sensorler': 'Radar ve Sensörler',
    'Agir Silah ve Muhimmatlar': 'Ağır Silah ve Mühimmatlar', 'Fuze Sistemleri': 'Füze Sistemleri',
}
CAT = {  # üst kategori -> kısa anahtar
    'Havacılık ve Uzay Sistemleri': 'hava', 'Deniz Araçları': 'deniz', 'Kara Araçları': 'kara', 'Silah Sistemleri': 'silah',
    'Radar ve Elektronik Harp Sistemleri': 'radar', 'Muhabere ve Elektronik Sistemler': 'muhabere',
    'Entegre Güvenlik Sistemleri': 'guvenlik', 'Simülatörler': 'simulator',
}

def fx(s):
    s = re.sub(r'\s+', ' ', str(s or '')).strip()
    return FIX.get(s, s)

def specs(t):
    """'[Grup] Ad : Değer | ...' -> [[grup, [[ad, değer], ...]], ...] (sıra korunur)"""
    out, idx = [], {}
    for part in str(t or '').split('|'):
        part = part.strip()
        if not part: continue
        m = re.match(r'^\[([^\]]+)\]\s*(.*)$', part)
        g, rest = (m.group(1).strip(), m.group(2)) if m else ('Genel', part)
        if ':' in rest:
            k, v = rest.split(':', 1)
        else:
            k, v = rest, ''
        k, v = k.strip(), v.strip()
        if not k or not v: continue
        if g not in idx:
            idx[g] = len(out); out.append([g, []])
        out[idx[g]][1].append([k, v])
    return out

def main(path):
    raw = json.load(open(path, encoding='utf-8'))
    seen, rows = set(), []
    for r in raw:
        name = fx(r[0])
        if not name or name.lower() in seen: continue
        seen.add(name.lower())
        top, sub = fx(r[1]), fx(r[2])
        rows.append([name, CAT.get(top, 'diger'), sub, fx(r[3]), fx(r[4]), specs(r[5]), fx(r[6]), 1 if fx(r[7]).lower().startswith('aktif') else 0])
    rows.sort(key=lambda x: (x[1], x[2], unicodedata.normalize('NFKD', x[0]).lower()))
    js = ('/* ------------------------------------------------------------------ inventory data (generated by tools/dt_import.py — do not edit)\n'
          '   Kaynak: Defence Turk Sistem Envanteri — https://www.defenceturk.tr/tr/sistem-envanteri (açık kaynak bilgiler).\n'
          '   Fields: [name, category, subcategory, maker, configurations, specs[[group,[[k,v]]]], users, active] */\n'
          'const ENV_SRC={name:"Defence Turk · Sistem Envanteri",url:"https://www.defenceturk.tr/tr/sistem-envanteri",date:"2026-10-12"};\n'
          'const ENV_DATA=' + json.dumps(rows, ensure_ascii=False, separators=(',', ':')) + ';\n')
    open('src/js/93-envanter-data.js', 'w', encoding='utf-8').write(js)
    print(len(rows), 'kayıt,', len(js) // 1024, 'KB')

if __name__ == '__main__':
    main(sys.argv[1] if len(sys.argv) > 1 else '/tmp/real/dt/raw.json')

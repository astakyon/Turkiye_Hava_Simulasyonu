#!/usr/bin/env python3
"""Writes the newest CHANGELOG.md entries to src/js/veri/surum-notlari-veri.js (shown in the game as release notes)."""
import json, re, sys, os
ROOT = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
N = int(sys.argv[1]) if len(sys.argv) > 1 else 8
text = open(os.path.join(ROOT, 'CHANGELOG.md'), encoding='utf-8').read()
out = []
for m in re.finditer(r'^## (V\d+\.\d+) — (\S+)(?: · ([^\n]+))?\n(.*?)(?=^## |\Z)', text, re.S | re.M):
    out.append({'v': m.group(1), 'd': m.group(2), 't': (m.group(3) or '').strip(), 'md': m.group(4).strip()})
    if len(out) >= N:
        break
js = ('/* generated by tools/relnotes.py from CHANGELOG.md — do not edit */\n'
      'const RELNOTES=' + json.dumps(out, ensure_ascii=False) + ';\n')
open(os.path.join(ROOT, 'src', 'js', 'veri', 'surum-notlari-veri.js'), 'w', encoding='utf-8').write(js)
print(len(out), 'entries')
